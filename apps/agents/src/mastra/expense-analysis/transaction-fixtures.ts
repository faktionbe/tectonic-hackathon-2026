function diningMonth(month: string, amounts: Array<number>, idPrefix: string) {
  return amounts.map((amount, index) =>
    expense({
      id: `${idPrefix}_${index + 1}`,
      amount,
      direction: 'DEBIT',
      bookingDate: `${month}-${String(10 + index).padStart(2, '0')}`,
      category: 'DINING',
      countryCode: 'BE',
      counterpartyId: 'party_restaurant',
    })
  );
}

